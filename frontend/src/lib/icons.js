export function icon(name, className = '') {
    const wrapper = document.createElement('span');
    wrapper.className = `icon ${className}`.trim();
    wrapper.innerHTML = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths[name] ?? ''}</svg>`;
    return wrapper;
}

export function hydrateIcons(root = document) {
    root.querySelectorAll('i[data-icon]').forEach((el) => el.replaceWith(icon(el.dataset.icon, el.className)));
}
